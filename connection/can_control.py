    def set_pp_state_and_verify(
        self,
        r2_ohm: int,
        r3_ohm: int,
        r2_on: bool,
        r3_on: bool,
        pp_state: bool,
        ev_sim: bool = True,
        timeout_s: float = PP_STATE_VERIFY_TIMEOUT_S,
        poll_interval_s: float = PP_STATE_VERIFY_POLL_INTERVAL_S,
    ) -> dict:
        """Like set_pp_state(), but afterwards waits for a 0x0500 feedback
        from the test system (charging station/SECC side, not from the
        test bench itself) that confirms the sent state (requires
        start_feedback_listener() to have been called). Returns the
        confirming feedback; raises PPStateNotConfirmedError if no
        matching feedback arrives within timeout_s (e.g. the switch did
        not close)."""
        self.set_pp_state(r2_ohm, r3_ohm, r2_on, r3_on, pp_state, ev_sim)
        expected = {
            "ev_sim": ev_sim,
            "r2_ohm": r2_ohm,
            "r3_ohm": r3_ohm,
            "r2_on": r2_on,
            "r3_on": r3_on,
            "pp_state": pp_state,
        }
        deadline = time.monotonic() + timeout_s
        while time.monotonic() < deadline:
            feedback = self.get_pp_feedback()
            if feedback == expected:
                return feedback
            time.sleep(poll_interval_s)
        raise PPStateNotConfirmedError(
            f"Test system did not confirm the sent PP/EVSim state: "
            f"expected {expected}, last received {self.get_pp_feedback()}"
        )
