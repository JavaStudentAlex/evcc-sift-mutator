"""SIFT-Inspired Pairwise Judge + Bradley-Terry Tournament Ranking.

Implements Stage 2 of the SIFT (Selective Iterative Fuzzing Tournament) architecture.
When multiple mutation candidates are generated by different mutator arms, this judge
evaluates candidate pairs, fits a Bradley-Terry preference model, and selects the
highest-ranked candidate to dispatch to the physical charging station.
"""
from __future__ import annotations

import json
import logging
import math
import urllib.request
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
from mutation.operators import MutationCandidate

logger = logging.getLogger("sift_judge")


class SIFTJudge:
    """Pairwise evaluator and Bradley-Terry tournament ranker."""

    def __init__(
        self,
        judge_model: str = "gemini-3.1-pro-preview",
        proxy_url: str = "http://localhost:8317/v1/chat/completions",
        proxy_key: str = "local-key",
    ):
        self.judge_model = judge_model
        self.proxy_url = proxy_url
        self.proxy_key = proxy_key

    def judge_pair_heuristic(self, cand_a: MutationCandidate, cand_b: MutationCandidate) -> str:
        """Deterministic heuristic judge based on safety criticality and novelty."""
        score_a = self._compute_heuristic_severity(cand_a)
        score_b = self._compute_heuristic_severity(cand_b)

        if score_a > score_b:
            return "A"
        elif score_b > score_a:
            return "B"
        return "TIE"

    def _compute_heuristic_severity(self, cand: MutationCandidate) -> float:
        """Assigns an engineering severity score based on the target invariant."""
        score = 1.0
        desc = (cand.description + " " + cand.rationale).lower()

        # Electrical / Thermal safety violations are highest priority
        if "negative current" in desc or "reverse power" in desc:
            score += 5.0
        if "100% soc" in desc and "current" in desc:
            score += 4.5
        if "overflow" in desc:
            score += 4.0
        if "skip" in desc and ("cable" in desc or "precharge" in desc):
            score += 4.2
        if "attenuation" in desc or "runid" in desc:
            score += 2.5
        if "extreme voltage" in desc:
            score += 3.8

        return score

    def fit_bradley_terry(self, num_candidates: int, comparisons: List[Tuple[int, int, str]], max_iter: int = 50) -> np.ndarray:
        """Solves Bradley-Terry model parameters using Iterative Minorization-Maximization.

        comparisons: list of (idx_a, idx_b, verdict) where verdict in ['A', 'B', 'TIE'].
        Returns theta vector of latent candidate scores.
        """
        w = np.zeros(num_candidates, dtype=np.float64)  # Win counts
        n_matrix = np.zeros((num_candidates, num_candidates), dtype=np.float64)  # Total matches

        for i, j, outcome in comparisons:
            if outcome == "A":
                w[i] += 1.0
            elif outcome == "B":
                w[j] += 1.0
            elif outcome == "TIE":
                w[i] += 0.5
                w[j] += 0.5
            n_matrix[i, j] += 1.0
            n_matrix[j, i] += 1.0

        # Initialize p vector uniformly
        p = np.ones(num_candidates, dtype=np.float64) / num_candidates

        for _ in range(max_iter):
            p_new = np.zeros_like(p)
            for i in range(num_candidates):
                denom = 0.0
                for j in range(num_candidates):
                    if i != j and n_matrix[i, j] > 0:
                        denom += n_matrix[i, j] / (p[i] + p[j])
                if denom > 0:
                    p_new[i] = w[i] / denom
                else:
                    p_new[i] = p[i]

            # Normalize to sum = 1
            if np.sum(p_new) > 0:
                p_new /= np.sum(p_new)
            if np.allclose(p, p_new, atol=1e-5):
                break
            p = p_new

        # Convert to log-scale theta centered at zero
        theta = np.log(np.maximum(p, 1e-12))
        theta -= np.mean(theta)
        return theta

    def rank_tournament(self, candidates: List[MutationCandidate]) -> Tuple[MutationCandidate, float, Dict[str, Any]]:
        """Runs an all-pairs round-robin tournament across candidates and ranks them."""
        if not candidates:
            raise ValueError("Candidate pool is empty")
        if len(candidates) == 1:
            return candidates[0], 1.0, {"theta": [0.0], "comparisons": []}

        comparisons = []
        n = len(candidates)

        for i in range(n):
            for j in range(i + 1, n):
                verdict = self.judge_pair_heuristic(candidates[i], candidates[j])
                comparisons.append((i, j, verdict))
                logger.debug(f"[SIFT Tournament] {candidates[i].arm} vs {candidates[j].arm} -> {verdict}")

        theta = self.fit_bradley_terry(n, comparisons)
        best_idx = int(np.argmax(theta))
        best_candidate = candidates[best_idx]
        best_score = float(theta[best_idx])

        logger.info(
            f"[SIFT Tournament Winner] #{best_idx} ({best_candidate.arm}): {best_candidate.description} (BT θ={best_score:.3f})"
        )

        return best_candidate, best_score, {
            "theta": theta.tolist(),
            "comparisons": comparisons,
            "winner_idx": best_idx,
        }
